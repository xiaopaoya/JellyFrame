ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT / 'palette.json').read_text(encoding='utf-8'))


def kebab(value):
    return re.sub(r'([A-Z])', r'-\1', value).lower()


def luminance(value):
    rgb = [int(value[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in rgb]
    return sum(v * weight for v, weight in zip(linear, (.2126, .7152, .0722)))


def contrast(a, b):
    lo, hi = sorted((luminance(a), luminance(b)))
    return (hi + .05) / (lo + .05)


css = ['/* Generated by generate_palette.py. Edit palette.json, then regenerate. */', ':root {']
for group in ('brand', 'logo', 'accent', 'neutral', 'material'):
    for name, value in data[group].items():
        css.append(f'  --jf-{group}-{kebab(name)}: {value};')
css.append('}')
for theme, selector in [('light', ':root, .jf-theme-light'), ('dark', '.jf-theme-dark')]:
    css.append(f'\n{selector} {{')
    for name, value in data['themes'][theme].items():
        css.append(f'  --jf-color-{kebab(name)}: {value};')
    css.append('}')
(ROOT / 'palette.css').write_text('\n'.join(css) + '\n', encoding='utf-8')

checks = []
for theme, colors in data['themes'].items():
    pairs = [('text', 'background'), ('text', 'surface'), ('text', 'surfaceRaised'),
             ('textMuted', 'background'), ('textMuted', 'surface'),
             ('link', 'background'), ('link', 'surface'),
             ('onPrimary', 'primary'), ('onPrimary', 'primaryHover'),
             ('onSelection', 'selection')]
    pairs += [(state, state + 'Surface') for state in ('success', 'warning', 'danger', 'info')]
    for foreground, background in pairs:
        ratio = contrast(colors[foreground], colors[background])
        assert ratio >= 4.5, (theme, foreground, background, ratio)
        checks.append(f'| {theme} | `{foreground}` / `{background}` | {ratio:.2f}:1 |')
    for foreground in ('focus', 'controlBorder'):
        for background in ('background', 'surface'):
            ratio = contrast(colors[foreground], colors[background])
            assert ratio >= 3, (theme, foreground, background, ratio)
            checks.append(f'| {theme} | `{foreground}` / `{background}`（非文本） | {ratio:.2f}:1 |')

