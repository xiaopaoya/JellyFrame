def swatch(x, y, width, height, color, title):
    ink = '#101820' if contrast(color, '#101820') >= 4.5 else '#FFFFFF'
    if contrast(color, ink) < 4.5:
        ink = '#000000'
    rect(x, y, width, height, color, 12)
    text(x + 16, y + height - 42, title, 14, ink, 600)
    text(x + 16, y + height - 18, color, 16, ink)


