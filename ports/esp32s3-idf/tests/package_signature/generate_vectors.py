"""Regenerate public, deterministic JFSG vectors with cryptography/OpenSSL.

Scalars 1 and 2 are deliberately public test keys, never product credentials.
Requires cryptography >= 43 for deterministic ECDSA. Not needed to run C++ tests.
"""
from pathlib import Path
import hashlib
import struct
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, utils


def emit(name, data):
    rows = [", ".join(f"0x{x:02x}" for x in data[i:i + 12]) for i in range(0, len(data), 12)]
    return f"inline constexpr std::array<std::uint8_t, {len(data)}> {name}{{{{\n    " + ",\n    ".join(rows) + "\n}};\n"


def text(value):
    raw = value.encode()
    return struct.pack("<H", len(raw)) + raw


key = ec.derive_private_key(1, ec.SECP256R1())
other = ec.derive_private_key(2, ec.SECP256R1()).public_key().public_numbers()
public = key.public_key().public_numbers()
key_id = bytes(range(0x10, 0x20))
bundle = b"JFAPPV0\0" + bytes(48)  # Parser fixture, not a complete installable app.
resource_hash = hashlib.sha256(b"public test resource").digest()
manifest = (text("crypto.test") + text("1.0.0") + struct.pack("<I", 7) +
            hashlib.sha256(bundle).digest() + struct.pack("<I", 1) +
            text("/a.txt") + resource_hash)
header = (b"JFSG\0\0\0\0" + struct.pack("<HHHHIHH", 1, 64, 1, 0, len(manifest), 64, 0) +
          key_id + bytes(24))
domain = b"JellyFrame Signed Package v1\0"
message = domain + header + manifest
signature_der = key.sign(message, ec.ECDSA(hashes.SHA256(), deterministic_signing=True))
key.public_key().verify(signature_der, message, ec.ECDSA(hashes.SHA256()))
r, s = utils.decode_dss_signature(signature_der)
raw = r.to_bytes(32, "big") + s.to_bytes(32, "big")
without_nul = key.sign(domain[:-1] + header + manifest,
                       ec.ECDSA(hashes.SHA256(), deterministic_signing=True))
r0, s0 = utils.decode_dss_signature(without_nul)
values = {
    "kKeyId": key_id, "kX": public.x.to_bytes(32, "big"), "kY": public.y.to_bytes(32, "big"),
    "kOtherX": other.x.to_bytes(32, "big"), "kOtherY": other.y.to_bytes(32, "big"),
    "kDomain": domain, "kHeader": header, "kManifest": manifest, "kSignature": raw,
    "kSignatureWithoutNul": r0.to_bytes(32, "big") + s0.to_bytes(32, "big"),
    "kSignatureDer": signature_der, "kBundle": bundle,
    "kBundleHash": hashlib.sha256(bundle).digest(), "kResourceHash": resource_hash,
    "kMessageHash": hashlib.sha256(message).digest(),
}
output = "// Generated by generate_vectors.py. Public test keys only.\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace signature_vectors {\n"
output += "\n".join(emit(name, data) for name, data in values.items())
output += "} // namespace signature_vectors\n"
Path(__file__).with_name("signature_vectors.h").write_text(output, encoding="utf-8")
print("message SHA-256:", hashlib.sha256(message).hexdigest())
